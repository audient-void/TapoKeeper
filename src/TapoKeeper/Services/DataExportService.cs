using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading.Tasks;
using CsvHelper;
using TapoKeeper.Models;

namespace TapoKeeper.Services;

/// <summary>
/// Service for exporting device data to various formats (Markdown, CSV)
/// </summary>
public class DataExportService
{
    private readonly AppConfig _config;

    public DataExportService(AppConfig config)
    {
        _config = config;
    }

    /// <summary>
    /// Export devices to Markdown format (human-readable with units)
    /// </summary>
    public async Task<string> ExportToMarkdownAsync(List<TapoDevice> devices, string? filePath = null)
    {
        var timestamp = DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss");
        filePath ??= $"tapokeeper_report_{DateTime.Now:yyyyMMdd_HHmmss}.md";

        var sb = new StringBuilder();
        sb.AppendLine("# TapoKeeper Power Report");
        sb.AppendLine($"**Generated:** {timestamp}");
        sb.AppendLine($"**Devices:** {devices.Count}");
        sb.AppendLine();

        // Summary section
        sb.AppendLine("## Summary");
        sb.AppendLine();

        var totalPowerW = devices.Where(d => d.CurrentPower != null).Sum(d => d.CurrentPower!.CurrentPowerW);
        var totalTodayKwh = devices.Where(d => d.CurrentPower != null).Sum(d => d.CurrentPower!.TodayEnergyKwh);
        var totalMonthKwh = devices.Where(d => d.CurrentPower != null).Sum(d => d.CurrentPower!.MonthEnergyKwh);
        var estimatedTodayCost = totalTodayKwh * _config.CostPerKwh;
        var estimatedMonthCost = totalMonthKwh * _config.CostPerKwh;

        sb.AppendLine($"- **Total Current Power:** {totalPowerW:F2} W");
        sb.AppendLine($"- **Total Today Energy:** {totalTodayKwh:F3} kWh (≈ ${estimatedTodayCost:F2})");
        sb.AppendLine($"- **Total Month Energy:** {totalMonthKwh:F3} kWh (≈ ${estimatedMonthCost:F2})");
        sb.AppendLine($"- **Cost Rate:** ${_config.CostPerKwh:F2} per kWh");
        sb.AppendLine();

        // Device details table
        sb.AppendLine("## Device Details");
        sb.AppendLine();
        sb.AppendLine("| Device | Model | Status | Power | Today | Month | Voltage | Current | IP Address |");
        sb.AppendLine("|--------|-------|--------|-------|-------|-------|---------|---------|------------|");

        foreach (var device in devices.OrderBy(d => d.Alias))
        {
            var status = device.DeviceOn ? "🟢 ON" : "🔴 OFF";
            var power = device.CurrentPower != null ? $"{device.CurrentPower.CurrentPowerW:F2} W" : "N/A";
            var today = device.CurrentPower != null ? $"{device.CurrentPower.TodayEnergyKwh:F3} kWh" : "N/A";
            var month = device.CurrentPower != null ? $"{device.CurrentPower.MonthEnergyKwh:F3} kWh" : "N/A";
            var voltage = device.CurrentPower != null ? $"{device.CurrentPower.CurrentVoltageV:F1} V" : "N/A";
            var current = device.CurrentPower != null ? $"{device.CurrentPower.CurrentCurrentA:F3} A" : "N/A";

            sb.AppendLine($"| {device.Alias} | {device.Model} | {status} | {power} | {today} | {month} | {voltage} | {current} | {device.IpAddress} |");
        }

        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine("*Generated by TapoKeeper - TP-Link Tapo Smart Plug Monitor*");

        var content = sb.ToString();
        await File.WriteAllTextAsync(filePath, content);

        Console.WriteLine($"✓ Report saved to: {filePath}");
        return filePath;
    }

    /// <summary>
    /// Export devices to CSV format (numeric values only)
    /// </summary>
    public async Task<string> ExportToCsvAsync(List<TapoDevice> devices, string? filePath = null)
    {
        filePath ??= $"tapokeeper_data_{DateTime.Now:yyyyMMdd_HHmmss}.csv";

        using var writer = new StreamWriter(filePath);
        using var csv = new CsvWriter(writer, CultureInfo.InvariantCulture);

        // Write CSV records
        var records = devices.Select(d => new
        {
            Timestamp = DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss"),
            Device = d.Alias,
            Model = d.Model,
            Status = d.DeviceOn ? "ON" : "OFF",
            PowerW = d.CurrentPower?.CurrentPowerW ?? 0,
            TodayKwh = d.CurrentPower?.TodayEnergyKwh ?? 0,
            MonthKwh = d.CurrentPower?.MonthEnergyKwh ?? 0,
            VoltageV = d.CurrentPower?.CurrentVoltageV ?? 0,
            CurrentA = d.CurrentPower?.CurrentCurrentA ?? 0,
            IpAddress = d.IpAddress,
            MacAddress = d.MacAddress,
        }).ToList();

        await csv.WriteRecordsAsync(records);

        Console.WriteLine($"✓ CSV data saved to: {filePath}");
        return filePath;
    }

    /// <summary>
    /// Generate a quick summary string for console output
    /// </summary>
    public string GenerateSummary(List<TapoDevice> devices)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"Found {devices.Count} devices:");

        var totalPowerW = devices.Where(d => d.CurrentPower != null).Sum(d => d.CurrentPower!.CurrentPowerW);
        var totalTodayKwh = devices.Where(d => d.CurrentPower != null).Sum(d => d.CurrentPower!.TodayEnergyKwh);

        sb.AppendLine($"Total Power: {totalPowerW:F2} W");
        sb.AppendLine($"Today's Energy: {totalTodayKwh:F3} kWh (≈ ${totalTodayKwh * _config.CostPerKwh:F2})");

        return sb.ToString();
    }
}
